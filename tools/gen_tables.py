"""Extracts the IQ codebook tables from ggml-common.h into a standalone C++ header for inferzero."""
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
src = open(src_path, encoding="utf-8").read()
names = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid",
         "kvalues_iq4nl", "iq1s_grid"]
defines = {"NGRID_IQ1S": None}
m = re.search(r"#define\s+NGRID_IQ1S\s+(\d+)", src)
defines["NGRID_IQ1S"] = int(m.group(1))

out = ["// IQ codebook tables, extracted from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).",
       "// Generated by gen_tables.py - do not edit.", "#pragma once", "#include <cstdint>", ""]
for name in names:
    pat = re.compile(r"GGML_TABLE_BEGIN\((\w+),\s*" + name + r",\s*(\w+)\)(.*?)GGML_TABLE_END\(\)", re.S)
    mm = pat.search(src)
    if not mm:
        raise SystemExit("table not found: " + name)
    ctype, size, body = mm.group(1), mm.group(2), mm.group(3)
    if size in defines:
        size = str(defines[size])
    body = re.sub(r"//[^\n]*", "", body)
    vals = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
    if len(vals) != int(size):
        raise SystemExit(f"{name}: expected {size} values, got {len(vals)}")
    out.append(f"static const {ctype} {name}[{size}] = {{")
    for i in range(0, len(vals), 8):
        out.append("  " + ", ".join(vals[i:i + 8]) + ",")
    out.append("};")
    out.append("")
open(out_path, "w", encoding="utf-8").write("\n".join(out))
print("wrote", out_path)
